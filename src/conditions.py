"""Step 2a: operating-condition assignment + per-condition normalization statistics (all in SQL).
Conditions: FD001/FD003 have one; FD002/FD004 have six (verified in EDA). Centroids come from
k-means on the op settings; each reading is assigned to its nearest centroid in SQL.
Normalization stats (mean/std per dataset x condition x sensor) use ONLY 'fit'-fold engines.
They need no RUL labels, so applying a target dataset's own stats is an unsupervised step."""
import numpy as np, pandas as pd
from sklearn.cluster import KMeans
from config import *

SCALE = (42.0, 0.84, 100.0)


def main():
    conn = connect()
    ops = pd.read_sql("""SELECT op_setting_1 o1, op_setting_2 o2, op_setting_3 o3 FROM sensor_readings r
                         JOIN engines e USING(engine_id) WHERE e.dataset IN ('FD002','FD004') AND e.split='train'""", conn)
    X = ops.to_numpy() / np.array(SCALE)
    km = KMeans(n_clusters=6, n_init=10, random_state=SEED).fit(X)
    cent = km.cluster_centers_ * np.array(SCALE)
    order = np.lexsort((cent[:, 2], cent[:, 1], cent[:, 0]))  # stable ids
    cent = cent[order]
    mean_cols = ",\n  ".join(f"avg({x}) AS m_{x}, stddev_samp({x}) AS sd_{x}" for x in SENSORS)
    z_cols = ",\n  ".join(f"(r.{x} - n.m_{x}) / NULLIF(n.sd_{x}, 0) AS z_{x}" for x in SENSORS)
    sql = f"""
DROP VIEW IF EXISTS z_readings; DROP TABLE IF EXISTS norm_stats, readings_cond, op_conditions CASCADE;
CREATE TABLE op_conditions (cond integer PRIMARY KEY, c1 real, c2 real, c3 real);
"""
    sql += "INSERT INTO op_conditions VALUES " + ",".join(
        f"({i},{c[0]:.6f},{c[1]:.6f},{c[2]:.6f})" for i, c in enumerate(cent)) + ";\n"
    sql += f"""
-- every reading + its operating condition (nearest centroid in scaled op-setting space)
CREATE TABLE readings_cond AS
SELECT r.engine_id, e.dataset, e.split, e.fold, r.cycle,
       CASE WHEN e.dataset IN ('FD001','FD003') THEN 0 ELSE c.cond END AS cond,
       r.op_setting_1, r.op_setting_2, r.op_setting_3,
       {", ".join("r."+x for x in SENSORS)}
FROM sensor_readings r
JOIN engines e USING (engine_id)
LEFT JOIN LATERAL (
   SELECT cond FROM op_conditions oc
   ORDER BY power((r.op_setting_1 - oc.c1)/{SCALE[0]},2) + power((r.op_setting_2 - oc.c2)/{SCALE[1]},2)
          + power((r.op_setting_3 - oc.c3)/{SCALE[2]},2) LIMIT 1) c ON TRUE;
ALTER TABLE readings_cond ADD PRIMARY KEY (engine_id, cycle);
CREATE INDEX ON readings_cond (dataset, cond);

-- per-condition normalization statistics from fit-fold engines only (no leakage)
CREATE TABLE norm_stats AS
SELECT dataset, cond, count(*) AS n,
  {mean_cols}
FROM readings_cond WHERE fold = 'fit' GROUP BY dataset, cond;
ALTER TABLE norm_stats ADD PRIMARY KEY (dataset, cond);

CREATE VIEW z_readings AS
SELECT r.engine_id, r.dataset, r.split, r.fold, r.cycle, r.cond,
  {z_cols}
FROM readings_cond r JOIN norm_stats n USING (dataset, cond);
ANALYZE readings_cond;
"""
    (SQL / "02_conditions.sql").write_text("-- GENERATED by src/conditions.py\n" + sql)
    with conn.cursor() as cur:
        cur.execute(sql)
    conn.commit()
    print(pd.read_sql("SELECT dataset, cond, count(*) n FROM readings_cond GROUP BY 1,2 ORDER BY 1,2", conn))
    conn.close()


if __name__ == "__main__":
    main()
