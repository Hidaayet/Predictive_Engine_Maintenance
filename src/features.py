"""Step 3: feature tables built with SQL window functions.
Windows are strictly causal (current row and earlier rows of the same engine), so a feature at
cycle t never uses data from t+1 or later. Two variants are built:
  features_raw  : raw sensors + raw operating settings (what a naive pipeline would use)
  features_norm : per-condition z-scores (stats from fit-fold engines), no op settings
Per shortlisted sensor: current value v_, rolling mean (5, 15), rolling std (5), rolling slope (15)."""
import json
from config import *

W_SHORT, W_LONG = 5, 15


def build_sql(sensors):
    def feats(src):  # src(s) -> SQL expr for the sensor value
        parts = []
        for s in sensors:
            e = src(s)
            parts += [f"{e} AS v_{s}",
                      f"avg({e}) OVER w5 AS m5_{s}",
                      f"COALESCE(stddev_samp({e}) OVER w5, 0) AS sd5_{s}",
                      f"avg({e}) OVER w15 AS m15_{s}",
                      f"COALESCE(regr_slope({e}, r.cycle) OVER w15, 0) AS sl15_{s}"]
        return ",\n  ".join(parts)

    win = f"""WINDOW w5  AS (PARTITION BY r.engine_id ORDER BY r.cycle ROWS BETWEEN {W_SHORT-1} PRECEDING AND CURRENT ROW),
       w15 AS (PARTITION BY r.engine_id ORDER BY r.cycle ROWS BETWEEN {W_LONG-1} PRECEDING AND CURRENT ROW)"""
    sql = f"""DROP TABLE IF EXISTS features_raw, features_norm;
CREATE TABLE features_raw AS
SELECT r.engine_id, r.cycle, r.op_setting_1::float8 AS op1, r.op_setting_2::float8 AS op2, r.op_setting_3::float8 AS op3,
  {feats(lambda s: f"r.{s}::float8")}
FROM readings_cond r
{win};
ALTER TABLE features_raw ADD PRIMARY KEY (engine_id, cycle);

CREATE TABLE features_norm AS
SELECT r.engine_id, r.cycle,
  {feats(lambda s: f"r.z_{s}::float8")}
FROM z_readings r
{win};
ALTER TABLE features_norm ADD PRIMARY KEY (engine_id, cycle);
ANALYZE features_raw; ANALYZE features_norm;
"""
    return sql


def main():
    sensors = json.load(open(OUT / "sensor_shortlist.json"))["sensors"]
    sql = build_sql(sensors)
    (SQL / "03_features.sql").write_text("-- GENERATED by src/features.py from outputs/sensor_shortlist.json\n" + sql)
    conn = connect()
    with conn.cursor() as cur:
        cur.execute(sql)
        cur.execute("SELECT count(*) FROM features_raw"); n1 = cur.fetchone()[0]
        cur.execute("SELECT count(*) FROM features_norm"); n2 = cur.fetchone()[0]
        cur.execute("SELECT count(*) FROM features_norm WHERE num_nulls(" + ",".join(f"v_{s}" for s in sensors) + ") > 0"); nn = cur.fetchone()[0]
    conn.commit(); conn.close()
    print(f"features_raw rows={n1}, features_norm rows={n2}, rows with null sensor value={nn}")


if __name__ == "__main__":
    main()
