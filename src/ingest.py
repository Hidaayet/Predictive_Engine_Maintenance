"""Step 1: load C-MAPSS into PostgreSQL, assign operating conditions, validate, write a data-quality report."""
import numpy as np, pandas as pd, io
from sklearn.cluster import KMeans
from sqlalchemy import text
from common import *

COLS = ["unit_id", "cycle"] + OPS + SENSORS

def copy_df(conn, df, table):
    buf = io.StringIO(); df.to_csv(buf, index=False, header=False); buf.seek(0)
    cur = conn.connection.cursor()
    cur.copy_expert(f"COPY {table} ({','.join(df.columns)}) FROM STDIN WITH CSV", buf)

def main():
    eng = get_engine()
    with eng.begin() as c:
        c.execute(text(open(ROOT / "sql/00_schema.sql").read()))
    frames, eng_rows, rul_rows, cond_rows = [], [], [], []
    for ds in ["FD001", "FD002", "FD003", "FD004"]:
        centroids = None
        for split in ["train", "test"]:
            df = pd.read_csv(RAW / f"{split}_{ds}.txt", sep=r"\s+", header=None, names=COLS)
            df.insert(0, "split", split); df.insert(0, "dataset", ds)
            n = df.groupby("unit_id").cycle.max().rename("n_cycles").reset_index()
            n.insert(0, "split", split); n.insert(0, "dataset", ds)
            if split == "test":
                n["true_rul_at_end"] = pd.read_csv(RAW / f"RUL_{ds}.txt", header=None)[0].values
            else:
                n["true_rul_at_end"] = pd.NA
            eng_rows.append(n); frames.append(df)
            # operating conditions: k-means on scaled settings, FITTED ON TRAIN ONLY, 6 clusters for multi-condition sets
            X = df[OPS].values / np.array([42.0, 0.84, 100.0])
            if split == "train":
                k = 6 if ds in ("FD002", "FD004") else 1
                km = KMeans(n_clusters=k, n_init=10, random_state=SEED).fit(X) if k > 1 else None
            cid = km.predict(X) if km is not None else np.zeros(len(df), int)
            cond_rows.append(df[["dataset", "split", "unit_id", "cycle"]].assign(condition_id=cid.astype(int)))
            # labels: train engines every cycle (RUL from last recorded cycle); test engines only final cycle
            if split == "train":
                lab = df[["dataset", "split", "unit_id", "cycle"]].copy()
                lab["rul_uncapped"] = lab.groupby("unit_id").cycle.transform("max") - lab.cycle
            else:
                last = df.groupby("unit_id").cycle.max().rename("last").reset_index()
                lab = df.merge(last, on="unit_id"); lab = lab[lab.cycle == lab["last"]][["dataset", "split", "unit_id", "cycle"]].copy()
                lab["rul_uncapped"] = lab.unit_id.map(n.set_index("unit_id").true_rul_at_end)
            lab["rul_capped"] = lab.rul_uncapped.clip(upper=RUL_CAP)
            rul_rows.append(lab)
    with eng.begin() as c:
        copy_df(c, pd.concat(eng_rows).astype({"true_rul_at_end": "Int64"})[["dataset", "split", "unit_id", "n_cycles", "true_rul_at_end"]], "engines")
        copy_df(c, pd.concat(frames), "sensor_readings")
        copy_df(c, pd.concat(rul_rows)[["dataset", "split", "unit_id", "cycle", "rul_uncapped", "rul_capped"]], "rul_labels")
        copy_df(c, pd.concat(cond_rows)[["dataset", "split", "unit_id", "cycle", "condition_id"]], "op_conditions")
    validate(eng)

def validate(eng):
    q = lambda s: pd.read_sql(s, eng)
    out = ["# Data quality report (auto-generated by src/ingest.py)\n"]
    out.append("## Rows and engines\n" + q("""SELECT e.dataset, e.split, count(*) engines, min(n_cycles) min_cycles, round(avg(n_cycles),1) mean_cycles, max(n_cycles) max_cycles,
        (SELECT count(*) FROM sensor_readings r WHERE r.dataset=e.dataset AND r.split=e.split) readings
        FROM engines e GROUP BY 1,2 ORDER BY 1,2""").to_markdown(index=False))
    checks = {
        "null sensor/setting values": "SELECT count(*) FROM sensor_readings WHERE " + " OR ".join(f"{c} IS NULL" for c in OPS + SENSORS),
        "engines with cycle gaps (cycle != 1..n)": "SELECT count(*) FROM (SELECT unit_id FROM sensor_readings GROUP BY dataset,split,unit_id HAVING max(cycle)<>count(*) OR min(cycle)<>1) t",
        "readings without a condition id": "SELECT count(*) FROM sensor_readings r LEFT JOIN op_conditions o USING(dataset,split,unit_id,cycle) WHERE o.condition_id IS NULL",
        "train engines whose RUL at last cycle != 0": "SELECT count(*) FROM rul_labels WHERE split='train' AND cycle=(SELECT max(cycle) FROM rul_labels l WHERE l.dataset=rul_labels.dataset AND l.split='train' AND l.unit_id=rul_labels.unit_id) AND rul_uncapped<>0",
        "duplicate (dataset,split,unit,cycle) rows": "SELECT count(*) FROM (SELECT 1 FROM sensor_readings GROUP BY dataset,split,unit_id,cycle HAVING count(*)>1) t",
    }
    out.append("\n\n## Integrity checks (all should be 0)\n")
    out.append("| check | violations |\n|---|---|\n" + "\n".join(f"| {k} | {int(q(s).iloc[0,0])} |" for k, s in checks.items()))
    out.append("\n\n## Operating conditions per dataset (train)\n" + q("""SELECT dataset, count(DISTINCT condition_id) n_conditions FROM op_conditions WHERE split='train' GROUP BY 1 ORDER BY 1""").to_markdown(index=False))
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "data_quality.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

if __name__ == "__main__":
    main()
