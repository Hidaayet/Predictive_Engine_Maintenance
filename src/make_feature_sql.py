"""Step 3a: generate sql/02_features.sql from the EDA shortlist (so the SQL is plain, reviewable, re-runnable)."""
import pandas as pd
from common import *
keep = pd.read_csv(ROOT / "results" / "sensor_shortlist.csv").sensor.tolist()
W, W2 = 10, 30
sel_norm, sel_roll, cols = [], [], []
for s in keep:
    sel_norm.append(f"(r.{s} - m.{s}_mu) / m.{s}_sd AS {s}_n")
for s in keep:
    cols += [f"{s}_raw", f"{s}_raw_rm{W}", f"{s}_raw_rs{W}", f"{s}_n", f"{s}_rm{W}", f"{s}_rs{W}", f"{s}_rm{W2}"]
    sel_roll += [
        f"{s}_raw",
        f"avg({s}_raw) OVER w{W} AS {s}_raw_rm{W}",
        f"COALESCE(stddev_samp({s}_raw) OVER w{W}, 0) AS {s}_raw_rs{W}",
        f"{s}_n",
        f"avg({s}_n) OVER w{W} AS {s}_rm{W}",
        f"COALESCE(stddev_samp({s}_n) OVER w{W}, 0) AS {s}_rs{W}",
        f"avg({s}_n) OVER w{W2} AS {s}_rm{W2}",
    ]
piv = ",\n  ".join(f"max(CASE WHEN n.sensor='{s}' THEN n.mu END) AS {s}_mu, max(CASE WHEN n.sensor='{s}' THEN n.sd END) AS {s}_sd" for s in keep)
sql = f"""-- Generated by src/make_feature_sql.py -- do not edit by hand.
-- Features per (dataset, split, unit_id, cycle). All rolling windows are CAUSAL (current + previous cycles only),
-- so a feature at cycle t never uses information from cycles after t.
--   *_raw      raw sensor value (no regime correction)       *_n   per-(dataset,condition) z-score (train-split stats)
--   *_rm{W}/{W2}  rolling mean of *_n                          *_rs{W}  rolling std of *_n   (window = {W} cycles)
DROP TABLE IF EXISTS features;
CREATE TABLE features AS
WITH m AS (
  SELECT n.dataset, n.condition_id,
  {piv}
  FROM norm_stats n GROUP BY n.dataset, n.condition_id
), base AS (
  SELECT r.dataset, r.split, r.unit_id, r.cycle, o.condition_id,
         r.op_setting_1, r.op_setting_2, r.op_setting_3,
         {", ".join(f"r.{s} AS {s}_raw" for s in keep)},
         {", ".join(sel_norm)}
  FROM sensor_readings r
  JOIN op_conditions o USING (dataset, split, unit_id, cycle)
  JOIN m ON m.dataset = r.dataset AND m.condition_id = o.condition_id
)
SELECT dataset, split, unit_id, cycle, condition_id, op_setting_1, op_setting_2, op_setting_3,
  {",\n  ".join(sel_roll)}
FROM base
WINDOW w{W} AS (PARTITION BY dataset, split, unit_id ORDER BY cycle ROWS BETWEEN {W-1} PRECEDING AND CURRENT ROW),
       w{W2} AS (PARTITION BY dataset, split, unit_id ORDER BY cycle ROWS BETWEEN {W2-1} PRECEDING AND CURRENT ROW);
ALTER TABLE features ADD PRIMARY KEY (dataset, split, unit_id, cycle);
"""
(ROOT / "sql" / "02_features.sql").write_text(sql)
(ROOT / "results" / "feature_columns.txt").write_text("\n".join(cols))
print(len(cols), "sensor feature columns")
